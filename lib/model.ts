// Token Radar — model "radar-2".
//
// One snapshot of the protocol universe in, one ranked board out. The board
// covers every slug in the snapshot's watchlist (the floor, never a ceiling)
// and every other pre-token protocol that is not a wrapped, staked, bridged
// or exchange product of a token that already trades. A protocol is
// pre-token when its record carries no token at all: no market cap, no
// CoinGecko id and no symbol. Live-token protocols are kept apart and shown
// with the market's own values, never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. No protocol
// name is ever special-cased; the same function scores every row:
//
//   base        = tvl_usd x 0.30            (a launch is priced off the value
//                                            already locked in the protocol)
//   category    = a multiple by category,   (different kinds of protocol
//                 0.70..1.20                earn different token multiples;
//                                            bridges and staking pools, the
//                                            lowest, rarely launch a token
//                                            of their own at all)
//   growth      = 1 + clamp(change_7d, -50, 150) / 100 x 0.60
//   maturity    = by age with no token:     (young protocols are unproven,
//                 0.75..0.90 in the first    proven ones earn more, and a
//                 90 days, rising to 1.10   protocol that has run for years
//                 at two years, then        with no token slowly loses
//                 easing back to 0.95       launch likelihood)
//   breadth     = 1.00..1.08 by chain count (more chains, wider distribution)
//   confidence  = 0.90..1.00                (a discount where the snapshot
//                                            leaves age or growth unknown)
//   implied     = max(1, round(base x category x growth x maturity
//                              x breadth x confidence))
//
// Age is the days from listed_at to the snapshot's as_of; an unknown age
// uses 365 days. A protocol that "records no token" is never claimed to
// have none: DefiLlama's record is not proof, and a token may exist that
// its record does not carry.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

